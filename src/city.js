function switchCity(id){
  if (!CITY_IDS.includes(id) || id === CITY_ID) return;
  try{ localStorage.setItem('osk3d.city', JSON.stringify(id)); }catch(e){}
  location.hash = id;
  setTimeout(() => location.reload(), 30);
}
window.addEventListener('hashchange', () => {
  const h = location.hash.slice(1);
  if (CITY_IDS.includes(h) && h !== CITY_ID){ try{ localStorage.setItem('osk3d.city', JSON.stringify(h)); }catch(e){} location.reload(); }
});
